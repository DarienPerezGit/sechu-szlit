import { readFileSync, readdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { sql } from "drizzle-orm";
import { verifyLegacyState } from "./legacy-verifier.js";
import type { Database } from "./index.js";
import { migrationSha256, normalizeMigration } from "./migration-utils.js";

const METADATA_TABLE = "__sechub_migrations";
const LEGACY_MIGRATION_COUNT = 7;
const MIGRATIONS_DIR = join(dirname(fileURLToPath(import.meta.url)), "migrations");
const LEGACY_MANIFEST = join(MIGRATIONS_DIR, "manifests", "legacy-public-v1.json");
const METADATA_DDL = `CREATE TABLE "${METADATA_TABLE}" (
  "id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "filename" text NOT NULL UNIQUE,
  "sha256" text NOT NULL,
  "applied_at" timestamptz NOT NULL DEFAULT now()
)`;

type Migration = { filename: string; contents: string; sha256: string };
type MetadataRow = { filename: string; sha256: string };
export type MigrationOptions = { adoptExisting?: boolean };

function loadMigrations(directory: string): Migration[] {
  return readdirSync(directory).filter((file) => file.endsWith(".sql")).sort()
    .map((filename) => {
      const contents = normalizeMigration(readFileSync(join(directory, filename), "utf8"));
      return { filename, contents, sha256: migrationSha256(contents) };
    });
}

function refuse(reason: string): never {
  throw new Error(`Migration refused: ${reason}`);
}

export async function runMigrations(
  db: Database,
  directory = MIGRATIONS_DIR,
  options: MigrationOptions = {},
): Promise<{ applied: number; adopted?: number }> {
  if (options.adoptExisting && resolve(directory) !== resolve(MIGRATIONS_DIR)) {
    refuse("explicit adoption requires the canonical shipped migration directory.");
  }
  const migrations = loadMigrations(directory);
  return db.transaction(async (tx) => {
    await tx.execute(sql`SELECT pg_advisory_xact_lock(hashtext('sechub:migrations:v1'))`);
    await tx.execute(sql`SET LOCAL search_path TO public`);
    const pinnedSchema = (await tx.execute(sql`SELECT current_schema() AS name`)).rows[0] as { name: string };
    if (pinnedSchema.name !== "public") refuse("migration transaction must use the public schema.");
    const objects = await tx.execute(sql.raw(`
      SELECT c.relname AS name
      FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = current_schema()
        AND c.relkind IN ('r', 'p', 'v', 'm', 'f', 'S')
        AND c.relname <> '${METADATA_TABLE}'
    `));
    const hasMetadata = (await tx.execute(sql.raw(`
      SELECT EXISTS (SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = current_schema() AND c.relname = '${METADATA_TABLE}') AS present
    `))).rows[0] as { present: boolean };
    let adopting = false;
    if (!hasMetadata.present && objects.rows.length > 0) {
      if (!options.adoptExisting) {
        refuse("an existing schema has no migration metadata; normal mode will not adopt it. Use pnpm db:migrate -- --adopt-existing.");
      }
      await verifyLegacyState({
        query: async (text) => ({ rows: (await tx.execute(sql.raw(text))).rows as any[] }),
      }, LEGACY_MANIFEST);
      adopting = true;
    }
    if (!hasMetadata.present) await tx.execute(sql.raw(METADATA_DDL));

    const records = await tx.execute(sql.raw(
      `SELECT filename, sha256 FROM "${METADATA_TABLE}" ORDER BY id`,
    ));
    let applied = records.rows as MetadataRow[];
    if (applied.length === 0 && objects.rows.length > 0 && !adopting) {
      refuse(`migration metadata is empty but the schema is not fresh; repair the metadata before retrying.`);
    }
    let adopted = 0;
    if (adopting) {
      const legacyMigrations = migrations.slice(0, LEGACY_MIGRATION_COUNT);
      for (const migration of legacyMigrations) {
        await tx.execute(sql.raw(
          `INSERT INTO "${METADATA_TABLE}" (filename, sha256) VALUES ('${migration.filename.replace(/'/g, "''")}', '${migration.sha256}')`,
        ));
      }
      applied = legacyMigrations;
      adopted = legacyMigrations.length;
    }
    if (applied.length > migrations.length) {
      refuse("migration metadata contains entries not present in the migration history.");
    }
    for (let index = 0; index < applied.length; index += 1) {
      const expected = migrations[index];
      const actual = applied[index];
      if (actual.filename !== expected.filename) {
        refuse(`migration metadata is non-contiguous at ${actual.filename}; expected ${expected.filename}.`);
      }
      if (actual.sha256 !== expected.sha256) {
        refuse(`integrity mismatch for ${actual.filename}; restore the recorded migration. Adoption is only for metadata-free canonical legacy schemas.`);
      }
    }

    for (const migration of migrations.slice(applied.length)) {
      await tx.execute(sql.raw(migration.contents));
      await tx.execute(sql.raw(
        `INSERT INTO "${METADATA_TABLE}" (filename, sha256) VALUES ('${migration.filename.replace(/'/g, "''")}', '${migration.sha256}')`,
      ));
    }
    return adopted
      ? { applied: migrations.length - applied.length, adopted }
      : { applied: migrations.length - applied.length };
  });
}
